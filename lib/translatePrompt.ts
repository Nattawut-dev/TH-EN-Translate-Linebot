export function buildTranslationPrompt(text: string) {
  const direction = detectDirection(text);
  const systemPrompt =
    direction === "TH_TO_EN" ? SYSTEM_PROMPT_TH_TO_EN : SYSTEM_PROMPT_EN_TO_TH;
  return { systemPrompt, direction };
}
