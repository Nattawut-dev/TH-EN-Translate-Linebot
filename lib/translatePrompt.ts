type Direction = "TH_TO_EN" | "EN_TO_TH";

function detectDirection(text: string): Direction {
  const hasThai = /[\u0E00-\u0E7F]/.test(text);
  return hasThai ? "TH_TO_EN" : "EN_TO_TH";
}

